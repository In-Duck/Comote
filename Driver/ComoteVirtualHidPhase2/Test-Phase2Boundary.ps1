$descriptorMatch = [regex]::Match(
    $source,
    "static\s+UCHAR\s+ComoteReportDescriptor\[\]\s*=\s*\{(?<body>.*?)\};",
    [Text.RegularExpressions.RegexOptions]::Singleline)
if (-not $descriptorMatch.Success) {
    throw "The Phase 2 HID report descriptor was not found."
}
$descriptorTokens = New-Object "System.Collections.Generic.List[int]"
foreach ($tokenMatch in [regex]::Matches(
    $descriptorMatch.Groups["body"].Value,
    "0x[0-9A-Fa-f]+|COMOTE_(?:KEYBOARD|MOUSE|ABSOLUTE_MOUSE)_REPORT_ID"
)) {
    switch ($tokenMatch.Value) {
        "COMOTE_KEYBOARD_REPORT_ID" {
            $descriptorTokens.Add(1)
        }
        "COMOTE_MOUSE_REPORT_ID" {
            $descriptorTokens.Add(2)
        }
        "COMOTE_ABSOLUTE_MOUSE_REPORT_ID" {
            $descriptorTokens.Add(3)
        }
        default {
            $descriptorTokens.Add(
                [Convert]::ToInt32(
                    $tokenMatch.Value.Substring(2),
                    16))
        }
    }
}
$reportSize = 0
$reportCount = 0
$reportId = 0
$reportBits = @{}
$reportInputFlags = @{}
$collectionDepth = 0
for ($index = 0; $index -lt $descriptorTokens.Count;) {
    $prefix = $descriptorTokens[$index]
    $index++
    if ($prefix -eq 0xFE) {
        throw "Long HID items are not allowed in the Phase 2 descriptor."
    }
    $dataSize = $prefix -band 3
    if ($dataSize -eq 3) {
        $dataSize = 4
    }
    if ($index + $dataSize -gt $descriptorTokens.Count) {
        throw "The Phase 2 HID report descriptor is truncated."
    }
    $value = 0
    for ($byteIndex = 0; $byteIndex -lt $dataSize; $byteIndex++) {
        $value = $value -bor (
            $descriptorTokens[$index] -shl (8 * $byteIndex))
        $index++
    }
    $itemType = ($prefix -shr 2) -band 3
    $itemTag = ($prefix -shr 4) -band 15
    if ($itemType -eq 1 -and $itemTag -eq 7) {
        $reportSize = $value
    }
    elseif ($itemType -eq 1 -and $itemTag -eq 8) {
        $reportId = $value
    }
    elseif ($itemType -eq 1 -and $itemTag -eq 9) {
        $reportCount = $value
    }
    elseif ($itemType -eq 0 -and $itemTag -eq 8) {
        if ($reportId -eq 0) {
            throw "A Phase 2 input item has no report ID."
        }
        if (-not $reportBits.ContainsKey($reportId)) {
            $reportBits[$reportId] = 0
            $reportInputFlags[$reportId] = @()
        }
        $reportBits[$reportId] += $reportSize * $reportCount
        $reportInputFlags[$reportId] += $value
    }
    elseif ($itemType -eq 0 -and $itemTag -eq 10) {
        $collectionDepth++
    }
    elseif ($itemType -eq 0 -and $itemTag -eq 12) {
        $collectionDepth--
        if ($collectionDepth -lt 0) {
            throw "The Phase 2 HID collection stack underflowed."
        }
    }
}
if ($collectionDepth -ne 0) {
    throw "The Phase 2 HID collections are unbalanced."
}
