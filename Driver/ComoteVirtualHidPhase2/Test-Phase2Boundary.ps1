        throw "The Phase 2 HID report ID is missing: $expectedReportId"
    }
    $actualReportBytes = 1 + [int][Math]::Ceiling(
        $reportBits[$expectedReportId] / 8)
    if ($actualReportBytes -ne $expectedReportBytes[$expectedReportId]) {
        throw (
            "The Phase 2 HID report size is invalid for report ID {0}: {1}" -f
            $expectedReportId,
            $actualReportBytes)
    }
    $actualInputFlags = $reportInputFlags[$expectedReportId] -join ","
    if ($actualInputFlags -ne $expectedInputFlags[$expectedReportId]) {
        throw (
            "The Phase 2 HID input flags are invalid for report ID {0}: {1}" -f
            $expectedReportId,
            $actualInputFlags)
    }
}

